//! ZenDesktop :: i18n.rs
//!
//! Internacionalizacion: 6 idiomas (ingles por defecto) con tabla plana de
//! strings. `Tr` es una estructura inmutable de `&'static str`; cada idioma
//! es una instancia estatica construida con la macro `tr!`. Los componentes
//! guardan una referencia `&'static Tr` (barata de copiar) y la refrescan al
//! cambiar de idioma.

/// Idioma de la interfaz.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Es,
    De,
    Fr,
    Pt,
    It,
}

impl Lang {
    pub const ALL: [Lang; 6] = [
        Lang::En,
        Lang::Es,
        Lang::De,
        Lang::Fr,
        Lang::Pt,
        Lang::It,
    ];

    /// Codigo ISO corto usado en config.toml.
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Es => "es",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Pt => "pt",
            Lang::It => "it",
        }
    }

    /// Desconocido o vacio -> ingles (idioma por defecto).
    pub fn from_code(s: &str) -> Lang {
        match s.trim().to_ascii_lowercase().as_str() {
            "es" => Lang::Es,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "pt" => Lang::Pt,
            "it" => Lang::It,
            _ => Lang::En,
        }
    }

    /// Nombre en su propio idioma (para el selector).
    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Es => "Español",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Pt => "Português",
            Lang::It => "Italiano",
        }
    }
}

